-- "Os dados estão atualizados?" feedback on the business side card.
-- One row per (user, business): a new vote replaces the previous one.
-- Read only by the server (service key) and by the internal panel; RLS has no policies on purpose.
create table if not exists public.business_feedback (
  id bigint generated by default as identity primary key,
  user_uid text not null references public.app_users(firebase_uid) on delete cascade,
  user_email text,
  business_id text not null,
  business_name text not null default '',
  business_snapshot jsonb not null default '{}'::jsonb,
  rating text not null check (rating in ('up', 'down')),
  issues text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_uid, business_id)
);

create index if not exists idx_business_feedback_rating_updated
  on public.business_feedback (rating, updated_at desc);

alter table public.business_feedback enable row level security;

